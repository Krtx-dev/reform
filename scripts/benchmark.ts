/**
 * Reproducible benchmark run. Writes docs/BENCHMARKS.md from ACTUAL executions.
 *   npm run benchmark
 * Uses an iteration budget with a generous time limit so the search is deterministic for the seed.
 */
import { writeFileSync } from "node:fs";
import os from "node:os";
import { runBenchmark, type BenchmarkOptions } from "../core/optimization/benchmark";
import { benchmarkMarkdown } from "../core/optimization/benchmarkReport";
import { BENCHMARK_DATASETS, BENCHMARK_PRODUCTS } from "../data/benchmarks/datasets";

const options: BenchmarkOptions = { objective: "material", seed: 42, maxIterations: 400, timeLimitMs: 60_000 };
const results = BENCHMARK_DATASETS.map((d) => {
  const r = runBenchmark({ ...d, products: BENCHMARK_PRODUCTS }, options);
  console.log(d.name.padEnd(34), r.rows.map((x) => `${x.algorithm}=${(x.utilization * 100).toFixed(2)}%/${x.products}p/${x.runtimeMs.toFixed(0)}ms/inv${x.invalidPlacements}`).join("  "));
  return r;
});

const env = `Node ${process.version} · ${os.platform()} ${os.arch()} · ${os.cpus()[0]?.model ?? "unknown CPU"}`;
const inputs = BENCHMARK_DATASETS.map((d) => `| ${d.name} | \`${d.id}\` | ${d.remnants.length} | ${d.remnants.reduce((s, r) => s + r.quantity, 0)} | ${(d.remnants.reduce((s, r) => s + r.width * r.height * r.quantity, 0) / 1e6).toFixed(2)} | ${d.demand.map((x) => `${x.productId.replace("p-", "")}×${x.max}`).join(", ")} | ${d.constraints.clearance}/${d.constraints.edgeMargin} |`).join("\n");

const md = `${benchmarkMarkdown(results, options, env)}
## Reproducible inputs

Datasets are generated deterministically in \`data/benchmarks/datasets.ts\` from fixed seeds (101–707); the demonstration factory is \`data/demo/inventory.ts\`. All use the eight built-in product templates in \`data/demo/products.ts\`.

| Dataset | id | Lines | Pieces | Area m² | Demand (max units) | Clearance/margin mm |
|---|---|---:|---:|---:|---|---|
${inputs}

## How to reproduce

\`\`\`bash
npm run benchmark        # rewrites this file
\`\`\`

Or in the app: Workspace → Benchmark → Run benchmark (uses a 3 s default time limit; raise it to match this file exactly).

This file was generated by \`scripts/benchmark.ts\` with settings: objective=material, seed=42, maxIterations=400, timeLimitMs=60000 (iteration budget binds first, so results are deterministic for the seed; runtimes vary by machine).
`;
writeFileSync(new URL("../docs/BENCHMARKS.md", import.meta.url), md);
console.log("wrote docs/BENCHMARKS.md");
